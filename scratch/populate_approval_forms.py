def populate_form(filename, data_dict):
    filepath = os.path.join(FOLDER, filename)
    doc = docx.Document(filepath)
    
    for t_idx, table_data in data_dict.items():
        if t_idx >= len(doc.tables):
            continue
        table = doc.tables[t_idx]
        for r_idx, row_data in table_data.items():
            if r_idx >= len(table.rows):
                continue
            row = table.rows[r_idx]
            for c_idx, text_val in row_data.items():
                if c_idx >= len(row.cells):
                    continue
                cell = row.cells[c_idx]
                cell.text = "" # Clear existing
                p = cell.paragraphs[0]
                p.alignment = WD_ALIGN_PARAGRAPH.LEFT
                run = p.add_run(text_val)
                run.font.size = Pt(10)
                run.font.name = "Calibri"
    
    doc.save(filepath)
    print(f"Successfully populated and saved: {filename}")

